#!/usr/bin/env python3
"""Generate paper/tables/tab_latency.tex and tab_fit.tex from code/data/v2/latency/*.csv (no hand-typed numbers)."""
import json
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
D = ROOT / "code" / "data" / "v2" / "latency"
T = ROOT / "paper" / "tables"
summ = pd.read_csv(D / "latency_summary.csv")
thr = pd.read_csv(D / "throughput.csv")
fit = pd.read_csv(D / "fit_times.csv")
hw = json.loads((D / "hardware.json").read_text())
nser = pd.read_csv(D / "latency_points.csv").groupby("dataset").series.nunique()
DS = [("k8s", "Kubernetes"), ("yahoo", "Yahoo S5"), ("cloud", "Cloud Monitoring")]
COMP = [("UASE-v2 (end-to-end)", "UASE-v2, end-to-end$^{a}$"), ("feature_update", "\\quad feature update$^{b}$"),
        ("Windowed RF", "Windowed RF"), ("Isolation Forest", "Isolation Forest"), ("LOF", "LOF"),
        ("ECOD", "ECOD"), ("HBOS", "HBOS"), ("Autoencoder", "Autoencoder"), ("Elliptic Envelope", "Elliptic Envelope"),
        ("Spectral Residual", "Spectral Residual$^{c}$"), ("Residual Z", "Residual Z$^{d}$")]
f = lambda v: "--" if pd.isna(v) else (f"{v:.3f}" if v < 0.1 else (f"{v:.2f}" if v < 10 else f"{v:.1f}"))
def kfmt(v):
    return f"{v/1000:,.0f}k" if v >= 1000 else f"{v:.0f}"
L = ["\\begin{table}[H]", "\\centering",
     "\\caption{Measured per-point streaming latency (ms; one new observation scored at a time) and batch throughput "
     f"(points/s, median over series) on an {hw['logical_cpus']}-vCPU {hw['hypervisor']} virtual machine "
     f"({hw['cpu_model']}, {float(hw['nominal_mhz'])/1000:.1f}\\,GHz, {hw['ram_gib']}\\,GiB RAM), single thread, Python {hw['python']}, "
     f"scikit-learn {hw['scikit_learn']}. Latencies exclude model training; detector rows exclude the feature update. "
     f"Series measured: Kubernetes {nser.get('k8s',0)}, Yahoo {nser.get('yahoo',0)}, Cloud {nser.get('cloud',0)}; first 200 test points of each. "
     "$^{a}$feature update + scaling + member detectors + ECDF fusion + threshold. "
     "$^{b}$Kubernetes: trailing 120 rows; univariate: recomputed over the full history (cost grows with history, Table~\\ref{tab:fit}). "
     "$^{c}$causal, recomputed on the full history up to $t$. "
     "$^{d}$throughput measured with a per-row Python loop (not vectorised).}",
     "\\label{tab:latency}", "\\small", "\\resizebox{\\textwidth}{!}{%",
     "\\begin{tabular}{llrrrrr}", "\\toprule",
     "Corpus & Component & Mean & Median & p95 & p99 & Throughput \\\\", "\\midrule"]
for i, (d, dn) in enumerate(DS):
    rows = [(c, lab) for c, lab in COMP if not summ[(summ.dataset == d) & (summ.component == c)].empty
            and summ[(summ.dataset == d) & (summ.component == c)]["n"].iloc[0] > 0]
    for j, (c, lab) in enumerate(rows):
        r = summ[(summ.dataset == d) & (summ.component == c)].iloc[0]
        tp = thr[(thr.dataset == d) & (thr.component == c)].points_per_s.median()
        L.append(f"{dn if j == 0 else ''} & {lab} & {f(r['mean'])} & {f(r['median'])} & {f(r['p95'])} & {f(r['p99'])} & {kfmt(tp) if pd.notna(tp) else '--'} \\\\")
    if i < len(DS) - 1:
        L.append("\\midrule")
L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
(T / "tab_latency.tex").write_text("% generated by code/scripts/make_latency_table.py\n" + "\n".join(L) + "\n")

# fit-time table
FC = [("UASE-v2 training pipeline (all channels + 4-fold OOF)", "Full pipeline (14 channels + 4-fold OOF)"),
      ("ALL channels, single fit each", "All channels, one fit each"),
      ("Windowed RF", "Windowed RF"), ("Windowed AE", "Windowed AE"), ("Autoencoder", "Autoencoder"),
      ("Elliptic Envelope", "Elliptic Envelope"), ("Isolation Forest", "Isolation Forest"), ("LOF", "LOF"),
      ("ECOD", "ECOD"), ("HBOS", "HBOS")]
L = ["\\begin{table}[H]", "\\centering",
     "\\caption{Measured training (fit) time in seconds on the same machine (median and maximum over the measured series), "
     "and the univariate feature-update cost as a function of history length (synthetic random walk, median of 20 runs).}",
     "\\label{tab:fit}", "\\small", "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{lrrrrrr}", "\\toprule",
     " & \\multicolumn{2}{c}{Kubernetes} & \\multicolumn{2}{c}{Yahoo S5} & \\multicolumn{2}{c}{Cloud} \\\\",
     "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
     "Component & median & max & median & max & median & max \\\\", "\\midrule"]
g = lambda v: "$<$0.001" if v < 0.0005 else f"{v:.3f}" if v < 0.1 else (f"{v:.2f}" if v < 10 else f"{v:.1f}")
for c, lab in FC:
    cells = []
    for d, _ in DS:
        s = fit[(fit.dataset == d) & (fit.component == c)].fit_ms / 1000
        cells += [g(s.median()), g(s.max())] if len(s) else ["--", "--"]
    L.append(f"{lab} & " + " & ".join(cells) + " \\\\")
sc_path = D / "feature_update_scaling.csv"
if sc_path.exists():
    sc = pd.read_csv(sc_path)
    L += ["\\midrule", "\\multicolumn{7}{l}{\\emph{Univariate feature update per new point (ms) vs.\\ history length}} \\\\",
          "History (points) & " + " & ".join(f"{int(h):,}" for h in sc.history_points) + " \\\\",
          "Median (ms) & " + " & ".join(g(v) for v in sc.median_ms) + " \\\\"]
L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
(T / "tab_fit.tex").write_text("% generated by code/scripts/make_latency_table.py\n" + "\n".join(L) + "\n")
print("ok")
